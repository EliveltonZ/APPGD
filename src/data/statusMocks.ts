import type { StatusProject, StatusProductionStage, StageName } from '../types/status'

function stage(
  status: StatusProductionStage['status'],
  inicio = '',
  fim = '',
  responsavel = '',
  pausa = '',
): StatusProductionStage {
  return { status, inicio, fim, responsavel, ...(pausa ? { pausa } : {}) }
}

